var LANG = 'ru';

/* Глобальные подстановки для t(): живут отдельно от vars, потому что
   задаются один раз на старте (из констант main.js), а не в точке
   вызова. Сейчас через них в подписи попадает процент комиссии —
   иначе константа TRADE_COMMISSION и текст «Комиссия (1%)» расходятся
   при каждом изменении ставки. */
var T_VARS = {};
function setTVar(key, val) { T_VARS[key] = val; }

function t(key, vars) {
  var dict = I18N[LANG] || I18N.ru;
  /* Ключ может прийти null/undefined (например, из переменной-режима,
     которую ещё не выставили). Раньше это падало на s.indexOf ниже и
     роняло весь вызывающий рендер — падать из-за отсутствующей строки
     незачем, отдаём пустую. */
  if (key == null) return '';
  var s = dict[key] != null ? dict[key] : (I18N.ru[key] || key);
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      s = s.split('{' + k + '}').join(vars[k]);
    });
  }
  /* Глобальные подстановки применяем вторыми: они не должны
     перетирать то, что передали в сам вызов. */
  Object.keys(T_VARS).forEach(function (k) {
    if (s.indexOf('{' + k + '}') >= 0) s = s.split('{' + k + '}').join(T_VARS[k]);
  });
  return s;
}

/* Применить язык ко всем статическим элементам. */
function applyI18n() {
  /* <html lang> следует за языком: скринридер переключает произношение. */
  try { document.documentElement.lang = LANG; } catch (e) {}
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    /* Тултип синхронно с aria: раньше кубик ника показывал «Generate»
       в русской локали из-за захардкоженного title в разметке. */
    if (el.tagName === 'BUTTON') el.title = el.getAttribute('aria-label');
  });
}
